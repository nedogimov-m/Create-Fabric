def native_item_ingredients(value):
    if isinstance(value, dict):
        if value.get("type") == "neoforge:compound":
            # Every selected pinned compound contains exactly one ordinary ingredient.
            # Do not weaken a future union/intersection into its first alternative.
            assert set(value) == {"type", "ingredients"} and len(value["ingredients"]) == 1
            return native_item_ingredients(value["ingredients"][0])
        return {key: native_item_ingredients(child) for key, child in value.items()}
    if isinstance(value, list):
        return [native_item_ingredients(child) for child in value]
    return value


def sync_optional_compat_assets(g):
    find, write_json = g["find"], g["write_json"]
    mods = set()
    for recipe in RECIPES:
        relative = "data/create/recipe/" + recipe
        data = json.loads(find(relative).read_text())
        conditions = data.pop("neoforge:conditions")
        assert len(conditions) == 1 and set(conditions[0]) == {"type", "modid"}
        assert conditions[0]["type"] == "neoforge:mod_loaded"
        mod = conditions[0]["modid"]
        mods.add(mod)
        data["fabric:load_conditions"] = [{"condition": "fabric:all_mods_loaded", "values": [mod]}]
        data = native_item_ingredients(data)
        # Native processing units are Fabric Transfer units, 81 per source millibucket.
        converted = g["modern_processing"](data)
        if recipe in SOURCE_PLATFORM_MILK_RECIPES:
            # These source outputs are NeoForgeMod.MILK, serialized as minecraft:milk.
            # Vanilla26.3 has no such fluid; AllFluids.MILK is the genuine Fabric owner.
            milk = [result for result in converted["results"] if result.get("fluid") == "minecraft:milk"]
            assert len(milk) == 1
            milk[0]["fluid"] = "create:milk"
        write_json(relative, converted)
    for relative in SOURCE_TAGS:
        write_json(relative, json.loads(find(relative).read_text()))
    return {"recipes": len(RECIPES), "source_tags": len(SOURCE_TAGS),
            "source_platform_milk_fluid_adaptations": len(set(RECIPES) & SOURCE_PLATFORM_MILK_RECIPES),
            "mod_ids": sorted(mods), "source_mod_conditions_preserved": True,
            "source_recipe_advancement_closure": 0,
            "foreign_mods_ported_or_installed": False, "runtime_verified": False}
